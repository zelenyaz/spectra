# ─── Utility functions ──────────────────────────────────────────────

die()  { printf '[FATAL] %s\n' "$*" >&2; exit 1; }
info() { printf '[INFO]  %s\n' "$*"; }
warn() { printf '[WARN]  %s\n' "$*" >&2; }

timeline() {
    local ts
    ts="$(date '+%Y-%m-%d %H:%M:%S')"
    printf '%s  %s\n' "${ts}" "$*" | tee -a "${OUTDIR}/timeline.log"
}

record_thp_timeline() {
    local enabled_path="/sys/kernel/mm/transparent_hugepage/enabled"
    local defrag_path="/sys/kernel/mm/transparent_hugepage/defrag"
    local enabled="unavailable"
    local defrag="unavailable"

    [[ -r "${enabled_path}" ]] && enabled="$(<"${enabled_path}")"
    [[ -r "${defrag_path}" ]] && defrag="$(<"${defrag_path}")"
    timeline "THP: ${enabled_path}=${enabled}"
    timeline "THP: ${defrag_path}=${defrag}"
}

resolve_path_from_base() {
    local base_dir="$1"
    local path="$2"

    if [[ "${path}" = /* ]]; then
        printf '%s\n' "${path}"
    else
        printf '%s/%s\n' "${base_dir}" "${path}"
    fi
}

validate_workload_source() {
    local workload_name="$1"
    local workdir="$2"
    local source_script="$3"
    local base_dir resolved_path

    [[ -n "${source_script}" ]] || return 0

    base_dir="${workdir:-${INVOCATION_DIR}}"
    resolved_path="$(resolve_path_from_base "${base_dir}" "${source_script}")"
    [[ -f "${resolved_path}" ]] || die "${workload_name} source script not found: ${source_script} (resolved: ${resolved_path})"
}

validate_workload_command() {
    local workload_name="$1"
    local cmd_name="$2"
    local workdir="$3"
    local -n workload_cmd="${cmd_name}"
    local base_dir resolved_cmd

    [[ ${#workload_cmd[@]} -gt 0 ]] || die "${workload_name} command is empty"

    base_dir="${workdir:-${INVOCATION_DIR}}"
    resolved_cmd="$(resolve_path_from_base "${base_dir}" "${workload_cmd[0]}")"
    [[ -x "${resolved_cmd}" || "${workload_cmd[0]}" != */* ]] || \
        die "${workload_name} executable not found or not executable: ${workload_cmd[0]} (resolved: ${resolved_cmd})"

    local cmd_basename
    cmd_basename="$(basename "${workload_cmd[0]}")"
    if [[ "${cmd_basename}" == "dramhit" ]]; then
        thp_enable_always || die "${workload_name}: failed to set THP knobs to 'always' for ${cmd_basename}"
        THP_ALWAYS_SET=1
    fi
}

proc_exe_basename() {
    local pid="$1"
    local exe_path

    [[ -d "/proc/${pid}" ]] || return 1
    exe_path="$(readlink -f "/proc/${pid}/exe" 2>/dev/null || true)"
    if [[ -n "${exe_path}" ]]; then
        basename "${exe_path}"
        return 0
    fi
    [[ -f "/proc/${pid}/comm" ]] || return 1
    tr -d '\n' < "/proc/${pid}/comm"
}

list_descendant_pids() {
    local root_pid="$1"
    local child_pid

    while read -r child_pid; do
        [[ -n "${child_pid}" ]] || continue
        printf '%s\n' "${child_pid}"
        list_descendant_pids "${child_pid}"
    done < <(pgrep -P "${root_pid}" 2>/dev/null || true)
}

find_workload_target_pid() {
    local root_pid="$1"
    local target_exe="$2"
    local candidate_pid candidate_exe

    if [[ -z "${target_exe}" ]]; then
        printf '%s\n' "${root_pid}"
        return 0
    fi

    candidate_exe="$(proc_exe_basename "${root_pid}" 2>/dev/null || true)"
    if [[ "${candidate_exe}" == "${target_exe}" ]]; then
        printf '%s\n' "${root_pid}"
        return 0
    fi

    while read -r candidate_pid; do
        [[ -n "${candidate_pid}" ]] || continue
        candidate_exe="$(proc_exe_basename "${candidate_pid}" 2>/dev/null || true)"
        if [[ "${candidate_exe}" == "${target_exe}" ]]; then
            printf '%s\n' "${candidate_pid}"
            return 0
        fi
    done < <(list_descendant_pids "${root_pid}")

    return 1
}

resolve_workload_profile_pid() {
    local pid_var_name="$1"
    local workload_name="$2"
    local root_pid="$3"
    local target_exe="$4"
    local deadline_ns now_ns candidate_pid

    if [[ -z "${target_exe}" ]]; then
        printf -v "${pid_var_name}" '%s' "${root_pid}"
        return 0
    fi

    # qp-llc-bench prints "READY pid=<pid>" to stdout and pauses until it
    # receives SIGUSR1. Read the PID from the per-workload stdout log instead
    # of scanning the process tree, then signal it to resume.
    if [[ "${target_exe}" == "qp-llc-bench" ]]; then
        local tag="${workload_name%%(*}"
        local stdout_log="${OUTDIR}/${tag,,}/stdout.log"
        local ready_line=""

        while true; do
            if [[ -f "${stdout_log}" ]]; then
                ready_line="$(grep -m1 '^READY pid=' "${stdout_log}" 2>/dev/null || true)"
                if [[ -n "${ready_line}" ]]; then
                    candidate_pid="${ready_line#READY pid=}"
                    candidate_pid="${candidate_pid%%[!0-9]*}"
                    [[ -n "${candidate_pid}" ]] && break
                fi
            fi

            kill -0 "${root_pid}" 2>/dev/null || \
                die "${workload_name} exited before READY marker appeared in ${stdout_log}"

            sleep 0.2
        done

        kill -USR1 "${candidate_pid}" || \
            die "${workload_name} failed to send SIGUSR1 to qp-llc-bench (pid=${candidate_pid})"
        printf -v "${pid_var_name}" '%s' "${candidate_pid}"
        return 0
    fi

    deadline_ns=$(( $(date +%s%N) + TARGET_PID_TIMEOUT_SEC * 1000000000 ))
    while true; do
        candidate_pid="$(find_workload_target_pid "${root_pid}" "${target_exe}" || true)"
        if [[ -n "${candidate_pid}" ]]; then
            printf -v "${pid_var_name}" '%s' "${candidate_pid}"
            return 0
        fi

        kill -0 "${root_pid}" 2>/dev/null || \
            die "${workload_name} exited before target executable ${target_exe} appeared"

        now_ns=$(date +%s%N)
        (( now_ns < deadline_ns )) || \
            die "${workload_name} timed out waiting for target executable ${target_exe}"
        sleep 0.2
    done
}

kill_workload_tree() {
    local root_pid="$1"
    local pid
    local -a descendants=()

    [[ -n "${root_pid}" ]] || return 0
    kill -0 "${root_pid}" 2>/dev/null || return 0

    while read -r pid; do
        [[ -n "${pid}" ]] || continue
        descendants+=("${pid}")
    done < <(list_descendant_pids "${root_pid}")

    for (( pid=${#descendants[@]}-1; pid>=0; pid-- )); do
        kill "${descendants[pid]}" 2>/dev/null || true
    done
    kill "${root_pid}" 2>/dev/null || true
}


