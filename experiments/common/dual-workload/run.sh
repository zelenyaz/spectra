#!/usr/bin/env bash
#
# run.sh — Dual-workload experiment with optional tiering baseline and profiling
#
# Runs two workloads simultaneously and profiles until both workloads finish.
# For tiering baselines (TPP/Colloid), the script includes a warmup phase with
# tiering disabled and then enables the kernel baseline mid-experiment. For the
# static baseline, workloads are launched with fixed NUMA memory binding and the
# experiment waits for completion directly after profiler startup. For the
# libtiermem baseline, workloads are launched under LD_PRELOAD with
# libtiermem.so; system tiering stays disabled throughout and DRAM pressure is
# managed by the library via TIERMEM_DRAM_BUDGET (no memeater). For the MTTM
# baseline, the helper sysctl knobs are programmed before workload launch and
# DRAM pressure is created by mttm_limit_local_dram_size (no memeater); each
# workload is launched via mttm_single_tenant_runner inside its own per-tenant
# memcg, and migration is enabled after the warmup/rebind phase.
#
# Usage:
#   sudo ./run.sh <config-file>
#
# Configs are generated by experiments/microbench/run-suite.sh and
# experiments/macrobench/run-suite.sh; see "Load configuration" below for the
# variables and their defaults.
#
# Flow:
#   1. System preparation (turbo, NMI watchdog, drop caches, disable swap)
#   2. Disable tiering (clean slate)
#   3. Optionally fill DRAM with memeater (usemem; skipped for libtiermem)
#   4. Start system-wide profilers (vvmstat, perf stat)
#   5. Launch both workloads simultaneously with initial core pinning
#      (static: also binds memory with numactl -m)
#      (libtiermem: also sets LD_PRELOAD and TIERMEM_* env vars)
#   6. Start per-PID profilers (parse_numa_maps x2)
#   7. Sleep WARMUP_SEC (tiering still disabled; non-static baselines)
#   8. Optionally rebind workload cores (taskset -acp; non-static baselines)
#   9. Enable tiering baseline (TPP or Colloid; kernel baselines only)
#  10. Wait for both workloads to finish (record individual timing)
#  11. Stop all profilers, free memory, clean up SHM, print summary
#
set -uo pipefail

