        "TIERMEM_MONITOR_CPU=${TIERMEM_MONITOR_CPU}"
        "TIERMEM_MIGRATE_CPU_START=${TIERMEM_MIGRATE_CPU_START}"
    )
    [[ -z "${TIERMEM_OBJ_THRESHOLD}" ]]   || _env_ref+=("TIERMEM_OBJ_THRESHOLD=${TIERMEM_OBJ_THRESHOLD}")
    [[ -z "${TIERMEM_EPOCH_SEC}" ]]       || _env_ref+=("TIERMEM_EPOCH_SEC=${TIERMEM_EPOCH_SEC}")
    [[ -z "${TIERMEM_LOG_LEVEL}" ]]       || _env_ref+=("TIERMEM_LOG_LEVEL=${TIERMEM_LOG_LEVEL}")
    [[ -z "${TIERMEM_PEBS_PERIOD:-}" ]]   || _env_ref+=("TIERMEM_PEBS_PERIOD=${TIERMEM_PEBS_PERIOD}")
    [[ -z "${TIERMEM_STORE_PERIOD:-}" ]]  || _env_ref+=("TIERMEM_STORE_PERIOD=${TIERMEM_STORE_PERIOD}")
    [[ -z "${TIERMEM_ALLLOAD_PERIOD:-}" ]] || _env_ref+=("TIERMEM_ALLLOAD_PERIOD=${TIERMEM_ALLLOAD_PERIOD}")
    [[ -z "${TIERMEM_OCR_INTERVAL:-}" ]]  || _env_ref+=("TIERMEM_OCR_INTERVAL=${TIERMEM_OCR_INTERVAL}")
    [[ -z "${TIERMEM_MIGRATE_THREADS:-}" ]] || _env_ref+=("TIERMEM_MIGRATE_THREADS=${TIERMEM_MIGRATE_THREADS}")
    [[ -z "${TIERMEM_HYSTERESIS:-}" ]]    || _env_ref+=("TIERMEM_HYSTERESIS=${TIERMEM_HYSTERESIS}")
    [[ -z "${TIERMEM_REG_THETA:-}" ]]     || _env_ref+=("TIERMEM_REG_THETA=${TIERMEM_REG_THETA}")
}

TENANT_ORDER_COUNTER=0

launch_workload() {
    local pid_var_name="$1"
    local workload_name="$2"
    local workdir="$3"
    local source_script="$4"
    local cores="$5"
    local mem_node="$6"
    local stdout_log="$7"
    local stderr_log="$8"
    local env_name="$9"
    local cmd_name="${10}"
    local -n workload_env="${env_name}"
    local -n workload_cmd="${cmd_name}"
    local -a numactl_cmd=(numactl -C "${cores}")
    local -a cgroup_cmd=()

    local -a env_cmd=()
    if [[ ${#workload_env[@]} -gt 0 ]]; then
        env_cmd=(env "${workload_env[@]}")
    fi

    if baseline_is_memtis; then
        cgroup_cmd=(cgexec -g "memory,cpuset:${MEMTIS_CGNAME}")
    fi

    TENANT_ORDER_COUNTER=$((TENANT_ORDER_COUNTER + 1))
    local tenant_order=${TENANT_ORDER_COUNTER}
    # Strip the "Wn(" / ")" wrapper from workload_name to produce a short tag
    # used by mttm_single_tenant_runner for cgroup naming and run_bench logging.
    local short_name="${workload_name##*\(}"
    short_name="${short_name%\)}"

    {
        if [[ -n "${workdir}" ]]; then
            cd "${workdir}" || die "${workload_name} failed to cd into ${workdir}"
        fi
        if [[ -n "${source_script}" ]]; then
            [[ -f "${source_script}" ]] || die "${workload_name} source script not found: ${source_script}"
            # shellcheck source=/dev/null
            set +u
            set --
            source "${source_script}" || die "${workload_name} failed to source ${source_script}"
            set -u
        fi
        if baseline_is_mttm; then
            # MTTM places memory via local_dram_string; do not bind with -m.
            # Core pinning is wrapped into the command passed to run_bench, since
            # mttm_single_tenant_runner forbids cpuset on the per-tenant memcg.
            mttm_single_tenant_runner "${tenant_order}" "${short_name}" -- \
                "${env_cmd[@]}" "${numactl_cmd[@]}" "${workload_cmd[@]}"
        else
            if [[ -n "${mem_node}" ]] && baseline_is_static; then
                numactl_cmd+=(-m "${mem_node}")
            fi
            exec "${cgroup_cmd[@]}" "${numactl_cmd[@]}" "${env_cmd[@]}" "${workload_cmd[@]}"
        fi
    } > "${stdout_log}" 2> "${stderr_log}" &

    printf -v "${pid_var_name}" '%s' "$!"
}

# Enable tiering without calling setup_common (which drops caches mid-experiment).
# Only loads modules and writes sysfs knobs.
enable_tiering() {
    local baseline="$1"
    case "${baseline}" in
        tpp)
            baseline_enable_tpp
            ;;
        colloid|alto)
            baseline_enable_colloid
            ;;
        memtis)
            baseline_enable_memtis
            ;;
        static)
            ;;
        *)
            die "Unknown baseline: ${baseline} (supported: static, tpp, colloid, alto, memtis)"
            ;;
    esac
}

start_scan_scale_controller() {
    local perf_log_path="$1"
    local scale_log_path="$2"

    PYTHONUNBUFFERED=1 python3 \
        "${ALTO_SCAN_SCALE}" \
        "${perf_log_path}" \
        > "${scale_log_path}" 2>&1 &
    SCAN_SCALE_PID=$!
    PROFILER_PIDS+=("${SCAN_SCALE_PID}")
    timeline "scan-scale controller started (PID=${SCAN_SCALE_PID})"
}

start_workload_pidstat() {
    local workload_label="$1"
    local profile_pid="$2"
    local log_path="$3"
    local pidstat_pid

    (( ENABLE_PIDSTAT )) || return 0
    if ! kill -0 "${profile_pid}" 2>/dev/null; then
        warn "${workload_label} profile_pid=${profile_pid} is not running; skipping pidstat"
        return 0
    fi

    pidstat -h -u -p "${profile_pid}" "${PIDSTAT_INTERVAL}" \
        > "${log_path}" 2>&1 &
    pidstat_pid=$!
    PROFILER_PIDS+=("${pidstat_pid}")
    timeline "pidstat started for ${workload_label} (PID=${pidstat_pid}, target=${profile_pid})"
}

start_workload_bpftrace() {
    local workload_label="$1"
    local profile_pid="$2"
    local log_path="$3"
    local bpf_pid

    (( ENABLE_BPFTRACE )) || return 0
    if ! kill -0 "${profile_pid}" 2>/dev/null; then
        warn "${workload_label} profile_pid=${profile_pid} is not running; skipping bpftrace"
        return 0
    fi

    "${BPFTRACE_BIN}" "${BPFTRACE_SCRIPT}" "${profile_pid}" \
        > "${log_path}" 2>&1 &
    bpf_pid=$!
    PROFILER_PIDS+=("${bpf_pid}")
    timeline "bpftrace migrate_pages started for ${workload_label} (PID=${bpf_pid}, target=${profile_pid})"
}

reset_alto_scan_scale() {
    local pte_scale_path="/proc/sys/kernel/numa_balancing_pte_scale"

    baseline_is_alto || return 0
    if [[ ! -w "${pte_scale_path}" ]]; then
        warn "Cannot reset ${pte_scale_path}"
        return 0
    fi

    printf '16\n' > "${pte_scale_path}" || {
        warn "Failed to reset ${pte_scale_path} to 16"
        return 0
    }
}

