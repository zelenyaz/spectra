cleanup() {
    (( CLEANUP_DONE )) && return
    CLEANUP_DONE=1

    info "Cleaning up..."

    # Kill workloads if still running.
    kill_workload_tree "${W1_PID}"
    kill_workload_tree "${W2_PID}"

    # Give profilers a moment to flush, then stop them
    sleep 1
    for pid in "${PROFILER_PIDS[@]}"; do
        if kill -0 "${pid}" 2>/dev/null; then
            kill "${pid}" 2>/dev/null || true
        fi
    done
    for pid in ${W1_PID} ${W2_PID} "${PROFILER_PIDS[@]}"; do
        [[ -n "${pid}" ]] && wait "${pid}" 2>/dev/null || true
    done

    reset_alto_scan_scale

    # Unload colloid-mon before tearing down memtis so it stops touching htmm
    # sysfs first.
    if (( COLLOID_MON_LOADED )); then
        memtis_unload_colloid_mon 2>/dev/null || true
        COLLOID_MON_LOADED=0
    fi

    if (( MEMTIS_PREPARED )); then
        baseline_disable_memtis 2>/dev/null || true
        MEMTIS_PREPARED=0
    fi

    if (( MTTM_PREPARED )); then
        dmesg > "${OUTDIR}/mttm-dmesg.log" 2>/dev/null || true
        baseline_disable_mttm 2>/dev/null || true
        MTTM_PREPARED=0
    fi

    # Free memory if we filled it
    if [[ -n "${DRAM_FREE_MIB}" ]] && baseline_uses_dram_fill; then
        freemem 2>/dev/null || true
    fi

    # Clean up libtiermem shared memory
    if baseline_is_libtiermem; then
        rm -f /dev/shm/tiermem_shm 2>/dev/null || true
    fi

    if (( THP_ALWAYS_SET )); then
        thp_restore_madvise 2>/dev/null || true
        THP_ALWAYS_SET=0
    fi
}
