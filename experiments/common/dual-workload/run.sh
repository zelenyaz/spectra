# Write per-workload timing
write_duration() {
    local name="$1" outdir="$2" start_ns="$3" post_warmup_ns="$4" end_ns="$5" rc="$6"
    local dur_s post_warmup_dur_s
    dur_s=$(awk "BEGIN {printf \"%.3f\", (${end_ns} - ${start_ns}) / 1000000000}")
    post_warmup_dur_s=$(awk "BEGIN {printf \"%.3f\", (${end_ns} - ${post_warmup_ns}) / 1000000000}")
    cat > "${outdir}/duration.txt" <<-EOF
	duration_sec=${dur_s}
	post_warmup_duration_sec=${post_warmup_dur_s}
	exit_code=${rc}
	start_epoch_ns=${start_ns}
	post_warmup_start_epoch_ns=${post_warmup_ns}
	end_epoch_ns=${end_ns}
	EOF
    echo "${dur_s}"
}

