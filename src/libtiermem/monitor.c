/* ── PEBS sample layout ── */
/* Fields follow sample_type bit order: IP(0), TID(1), ADDR(3), CPU(7) */
struct pebs_sample {
    struct perf_event_header header;
    uint64_t ip;           /* PERF_SAMPLE_IP   (bit 0) */
    uint32_t pid, tid;     /* PERF_SAMPLE_TID  (bit 1) */
    uint64_t addr;         /* PERF_SAMPLE_ADDR (bit 3) */
    uint32_t cpu, res;     /* PERF_SAMPLE_CPU  (bit 7) */
};

/*
 * store_sample layout: same fields as pebs_sample, plus weight at the tail.
 * sample_type bits enabled: IP(0) | TID(1) | ADDR(3) | CPU(7) | WEIGHT(14).
 */
struct pebs_store_sample {
    struct perf_event_header header;
    uint64_t ip;
    uint32_t pid, tid;
    uint64_t addr;
    uint32_t cpu, res;
    uint64_t weight;
};

static void cleanup_pebs_events(void)
{
    for (int cpu = 0; cpu < NUM_CPUS_PER_NODE; cpu++) {
        if (g_monitor.pebs_mmap[cpu]) {
            munmap(g_monitor.pebs_mmap[cpu], g_monitor.pebs_mmap_size);
            g_monitor.pebs_mmap[cpu] = NULL;
        }
        if (g_monitor.pebs_fd[cpu] >= 0) {
            close(g_monitor.pebs_fd[cpu]);
            g_monitor.pebs_fd[cpu] = -1;
        }
    }
}

static void cleanup_pebs_store_events(void)
{
    for (int cpu = 0; cpu < NUM_CPUS_PER_NODE; cpu++) {
        if (g_monitor.pebs_store_mmap[cpu]) {
            munmap(g_monitor.pebs_store_mmap[cpu], g_monitor.pebs_mmap_size);
            g_monitor.pebs_store_mmap[cpu] = NULL;
        }
        if (g_monitor.pebs_store_fd[cpu] >= 0) {
            close(g_monitor.pebs_store_fd[cpu]);
            g_monitor.pebs_store_fd[cpu] = -1;
        }
    }
}

static void cleanup_ocr_events(void)
{
    for (int i = 0; i < g_monitor.ocr_proc_count; i++) {
        if (g_monitor.ocr_procs[i].fd_demand_data_rd >= 0) {
            close(g_monitor.ocr_procs[i].fd_demand_data_rd);
            g_monitor.ocr_procs[i].fd_demand_data_rd = -1;
        }
        if (g_monitor.ocr_procs[i].fd_demand_rfo >= 0) {
            close(g_monitor.ocr_procs[i].fd_demand_rfo);
            g_monitor.ocr_procs[i].fd_demand_rfo = -1;
        }
        if (g_monitor.ocr_procs[i].fd_hw_data_pf >= 0) {
            close(g_monitor.ocr_procs[i].fd_hw_data_pf);
            g_monitor.ocr_procs[i].fd_hw_data_pf = -1;
        }
        if (g_monitor.ocr_procs[i].fd_hw_rfo_pf >= 0) {
            close(g_monitor.ocr_procs[i].fd_hw_rfo_pf);
            g_monitor.ocr_procs[i].fd_hw_rfo_pf = -1;
        }
    }
    g_monitor.ocr_proc_count = 0;
}

static void cleanup_imc_events(void)
{
    for (int node = 0; node < NUM_NODES; node++) {
        for (int ch = 0; ch < NUM_IMC_CHANNELS; ch++) {
            if (g_monitor.imc_wr_fds[node][ch] >= 0) {
                close(g_monitor.imc_wr_fds[node][ch]);
                g_monitor.imc_wr_fds[node][ch] = -1;
            }
            if (g_monitor.imc_rd_fds[node][ch] >= 0) {
                close(g_monitor.imc_rd_fds[node][ch]);
                g_monitor.imc_rd_fds[node][ch] = -1;
            }
        }
    }
}

static void init_ocr_attr(struct perf_event_attr *attr, uint64_t config1,
                          bool start_disabled)
{
    memset(attr, 0, sizeof(*attr));
    attr->type = PERF_TYPE_RAW;
    attr->size = sizeof(*attr);
    attr->config = OCR_EVENT_CONFIG;
    attr->config1 = config1;
    attr->sample_type = PERF_SAMPLE_IDENTIFIER;
    attr->read_format = PERF_FORMAT_TOTAL_TIME_ENABLED |
                        PERF_FORMAT_TOTAL_TIME_RUNNING;
    attr->disabled = start_disabled ? 1 : 0;
    attr->exclude_kernel = 1;
    attr->inherit = 1;
}

/* ── PMU event setup ── */

static int setup_pebs_events(void)
{
    g_monitor.pebs_mmap_size = (RING_BUFFER_PAGES + 1) * TM_PAGE_SIZE;

    /* Only monitor Node 0 CPUs — workloads are pinned there */
    for (int cpu = 0; cpu < NUM_CPUS_PER_NODE; cpu++) {
        struct perf_event_attr attr;
        memset(&attr, 0, sizeof(attr));
        attr.type           = PERF_TYPE_RAW;
        attr.size           = sizeof(attr);
        attr.config         = 0x20D1;  /* MEM_LOAD_RETIRED.L3_MISS */
        attr.sample_period  = g_config.pebs_period;
        attr.sample_type    = PERF_SAMPLE_IP | PERF_SAMPLE_ADDR |
                              PERF_SAMPLE_CPU | PERF_SAMPLE_TID;
        attr.read_format    = PERF_FORMAT_TOTAL_TIME_ENABLED |
                              PERF_FORMAT_TOTAL_TIME_RUNNING;
        attr.precise_ip     = 3;
        attr.disabled       = 1;
        attr.exclude_kernel = 1;
        attr.exclude_hv     = 1;
        attr.mmap           = 1;

        int fd = sys_perf_event_open(&attr, -1, cpu, -1, 0);
        if (fd < 0) {
            TM_ERR("Failed to open PEBS event on CPU %d: %s", cpu, strerror(errno));
            cleanup_pebs_events();
            return -1;
        }

        /* mmap ring buffer */
        void *base = mmap(NULL, g_monitor.pebs_mmap_size,
                          PROT_READ | PROT_WRITE, MAP_SHARED, fd, 0);
        if (base == MAP_FAILED) {
            TM_ERR("Failed to mmap PEBS ring buffer on CPU %d: %s",
                   cpu, strerror(errno));
            close(fd);
            cleanup_pebs_events();
            return -1;
        }

        g_monitor.pebs_fd[cpu] = fd;
        g_monitor.pebs_mmap[cpu] = (struct perf_event_mmap_page *)base;
    }

    TM_DBG("PEBS events opened on CPUs 0-%d", NUM_CPUS_PER_NODE - 1);
    return 0;
}

static int setup_pebs_store_events(void)
{
    g_monitor.pebs_mmap_size = (RING_BUFFER_PAGES + 1) * TM_PAGE_SIZE;

    for (int cpu = 0; cpu < NUM_CPUS_PER_NODE; cpu++) {
        struct perf_event_attr attr;
        memset(&attr, 0, sizeof(attr));
        attr.type           = PERF_TYPE_RAW;
        attr.size           = sizeof(attr);
        /* MEM_TRANS_RETIRED.STORE_SAMPLE: EventCode=0xcd, UMask=0x02 */
        attr.config         = (0x02ULL << 8) | 0xcd;
        attr.sample_period  = g_config.store_period;
        attr.sample_type    = PERF_SAMPLE_IP   | PERF_SAMPLE_TID  |
                              PERF_SAMPLE_ADDR | PERF_SAMPLE_CPU  |
                              PERF_SAMPLE_WEIGHT;
        attr.read_format    = PERF_FORMAT_TOTAL_TIME_ENABLED |
                              PERF_FORMAT_TOTAL_TIME_RUNNING;
        attr.precise_ip     = 3;
        attr.disabled       = 1;
        attr.exclude_kernel = 1;
        attr.exclude_hv     = 1;
        attr.mmap           = 1;

        int fd = sys_perf_event_open(&attr, -1, cpu, -1, 0);
        if (fd < 0) {
            TM_ERR("Failed to open store PEBS on CPU %d: %s",
                   cpu, strerror(errno));
            cleanup_pebs_store_events();
            return -1;
        }
        void *base = mmap(NULL, g_monitor.pebs_mmap_size,
                          PROT_READ | PROT_WRITE, MAP_SHARED, fd, 0);
        if (base == MAP_FAILED) {
            TM_ERR("Failed to mmap store PEBS on CPU %d: %s",
                   cpu, strerror(errno));
            close(fd);
            cleanup_pebs_store_events();
            return -1;
        }
        g_monitor.pebs_store_fd[cpu]   = fd;
        g_monitor.pebs_store_mmap[cpu] = (struct perf_event_mmap_page *)base;
    }
    TM_DBG("Store PEBS events opened on CPUs 0-%d", NUM_CPUS_PER_NODE - 1);
    return 0;
}

