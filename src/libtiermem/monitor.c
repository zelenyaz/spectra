/* Per-object epoch-end derived terms used only inside
 * compute_per_object_bw_new — kept off mem_object_t so the struct stays lean. */
struct obj_derived {
    double demand_data_rd;
    double hw_data_pf;          /* HW-prefetch share of total_data_pf (per object) */
    double sw_data_pf;          /* SW-prefetch share of total_data_pf (per object) */
    double demand_rfo;
    double hw_rfo_pf;
    double store_hit_load;
    double avg_store_lat;
    double reg_load_raw;
    double reg_load;
    double reg_store_raw;
    double reg_store;
    double w_hwpf;              /* per-object weight for the HW-prefetch pool split */
};

static void compute_per_object_bw_new(mem_object_t **arr, int n, double T)
{
    struct obj_derived *d = real_calloc((size_t)n, sizeof(*d));
    if (!d) return;

    /* Saturation threshold for per-object regularity: values below theta are
     * snapped to 0 (treated as fully irregular), values above 1-theta are
     * snapped to 1 (treated as fully regular). When every object in a process
     * saturates to 0, the regularity-weighted denominator collapses and we
     * fall back to dividing the per-process prefetch totals equally. */
    const double theta = g_config.reg_theta;

    /* Per-proc accumulators. Sized to MAX_PROCS — we index by ocr_procs slot. */
    double S_load_samples[MAX_PROCS]= {0};
    double S_allload[MAX_PROCS]     = {0};
    double S_pf_samples[MAX_PROCS]  = {0};
    double S_hwpf_w[MAX_PROCS]      = {0};
    double S_store_lat_sum[MAX_PROCS] = {0};
    double S_rfo_reg[MAX_PROCS]     = {0};
    double S_demand_rfo[MAX_PROCS]  = {0};
    double S_hw_rfo_pf[MAX_PROCS]   = {0};
    int    N_proc[MAX_PROCS]        = {0};

    /* Pass 0 — per-proc PEBS load-sample totals (attribution denominator) */
    for (int i = 0; i < n; i++) {
        mem_object_t *o = arr[i];
        int p = proc_slot_for(o->pid);
        if (p < 0) continue;
        S_load_samples[p] += (double)o->load_sample_count;
        S_allload[p]      += (double)o->allload_sample_count;
        S_pf_samples[p]   += (double)o->pf_sample_count;
    }

    /* Process-wide ratio: SW-prefetch share of all_loads samples.
     * The OCR.TOTAL_DATA_PF.L3_MISS magnitude (carried in epoch_hw_data_pf
     * after the mask was widened in Task 1) is split into:
     *   total_data_swpf[p] = total_pf * (pf_samples * 2 / allload_samples)
     *   total_data_hwpf[p] = total_pf - swpf
     * Falls back to all-HW if allload_samples is 0 (no PEBS coverage).
     * pf_samples * 2 since a swpf is usually followed by a normal load */
    double total_data_hwpf[MAX_PROCS];
    double total_data_swpf[MAX_PROCS];
    for (int p = 0; p < MAX_PROCS; p++) {
        double total = (double)g_monitor.ocr_procs[p].epoch_hw_data_pf;
        double ratio = (S_allload[p] > 0.0)
                       ? S_pf_samples[p] * 2 / S_allload[p]
                       : 0.0;
        ratio = ratio > 1.0 ? 1.0 : ratio;
        total_data_swpf[p] = total * ratio;
        total_data_hwpf[p] = total - total_data_swpf[p];
    }

    /* Pass 1 — primitives + regularity + per-proc bases.
     *
     * demand_data_rd is OCR-anchored: the process-wide total comes from
     * OCR.DEMAND_DATA_RD.L3_MISS (a counting event, correct magnitude even
     * under PEBS multiplexing and free of the semantic inflation of
     * MEM_LOAD_RETIRED.L3_MISS).  PEBS load samples are used only as
     * per-object attribution weights within that total. */
    for (int i = 0; i < n; i++) {
        mem_object_t *o = arr[i];

        int p = proc_slot_for(o->pid);
        if (p >= 0 && S_load_samples[p] > 0.0) {
            double ocr_total = (double)g_monitor.ocr_procs[p].epoch_demand_data_rd;
            d[i].demand_data_rd = ocr_total * (double)o->load_sample_count /
                                  S_load_samples[p];
        }
        d[i].avg_store_lat = o->store_sample_count
                           ? (double)o->store_lat_sum / (double)o->store_sample_count
                           : 0.0;
        double rl = regularity(o->load_stride_bins);
        double rs = regularity(o->store_stride_bins);
        d[i].reg_load_raw = rl;
        d[i].reg_store_raw = rs;
        d[i].reg_load  = regularity_theta_gate(rl, theta);
        d[i].reg_store = regularity_theta_gate(rs, theta);

#ifdef TIERMEM_DEBUG_REGULARITY
        debug_dump_stride_bins(o);
#endif

        if (p < 0) continue;
        N_proc[p]   += 1;

        /* HW-prefetch attribution weight.  demand_data_rd alone under-weights
         * SW-prefetched streams: their prefetch beats the demand load to the
         * line, so the load hits cache and is not an L3 miss, collapsing their
         * demand-miss share even though they stream at full bandwidth.  Add an
         * estimate of retired SW-prefetch lines (pf_sample_count * allload
         * period; period-independent in expectation) so such objects can claim
         * their share of the HW-prefetch pool.  pow(reg_load, gamma) gates the
         * whole weight on stream regularity so irregular (random) objects, which
         * trigger little HW prefetch, are sharply suppressed. */
        double pf_lines = (double)o->pf_sample_count
                        * (double)g_config.allload_period;
        d[i].w_hwpf = pow(d[i].reg_load, g_config.pf_reg_gamma)
                    * (d[i].demand_data_rd + g_config.pf_sw_kappa * pf_lines);
        S_hwpf_w[p] += d[i].w_hwpf;
        S_store_lat_sum[p] += (double)o->store_lat_sum;
    }

    /* Pass 3 (hw_data_pf, demand_rfo) + Pass-3-post sums */
    for (int i = 0; i < n; i++) {
        mem_object_t *o = arr[i];
        int p = proc_slot_for(o->pid);
        if (p < 0) continue;
        proc_ocr_t *po = &g_monitor.ocr_procs[p];

        d[i].hw_data_pf = (S_hwpf_w[p] > 0.0)
            ? total_data_hwpf[p] * d[i].w_hwpf / S_hwpf_w[p]
            : (N_proc[p] > 0
               ? total_data_hwpf[p] / (double)N_proc[p]
               : 0.0);

        /* SW-prefetch: distribute the SW share of total_data_pf across
         * objects of the same process proportional to per-object pf_sample
         * count (each retired PREFETCH* uop traces back to the object). */
        d[i].sw_data_pf = (S_pf_samples[p] > 0.0)
            ? total_data_swpf[p]
              * (double)o->pf_sample_count / S_pf_samples[p]
            : 0.0;

        d[i].demand_rfo = (S_store_lat_sum[p] > 0.0)
            ? (double)po->epoch_demand_rfo
              * (double)o->store_lat_sum / S_store_lat_sum[p]
            : 0.0;

        S_rfo_reg[p]    += d[i].demand_rfo * d[i].reg_store;
        S_demand_rfo[p] += d[i].demand_rfo;
    }

    /* Pass 4 — hw_rfo_pf + accumulate S_hw_rfo_pf */
    for (int i = 0; i < n; i++) {
        mem_object_t *o = arr[i];
        int p = proc_slot_for(o->pid);
        if (p < 0) continue;
        proc_ocr_t *po = &g_monitor.ocr_procs[p];

        d[i].hw_rfo_pf = (S_rfo_reg[p] > 0.0)
            ? (double)po->epoch_hw_rfo_pf
              * (d[i].demand_rfo * d[i].reg_store) / S_rfo_reg[p]
            : (N_proc[p] > 0
               ? (double)po->epoch_hw_rfo_pf / (double)N_proc[p]
               : 0.0);
        S_hw_rfo_pf[p] += d[i].hw_rfo_pf;
    }

    /* Pass 5 — system-wide residual store_hit_load.
     *
     * Ground truth: UNC_M_CAS_COUNT.WR (iMC WR CAS) — total writes that reach
     * DRAM across all channels on all sockets, in cacheline units.  The
     * residual after subtracting system-wide demand_rfo + hw_rfo_pf is
     * attributed to store-hit loads (RFO-fetched lines that absorb later
     * stores).  Distribute that residual across all objects proportionally
     * to (demand_data_rd + hw_data_pf) * store_sample_count: store-hit
     * fetches ride on top of read traffic, but only on objects that are
     * actually being stored to. */
    uint64_t imc_wr_cas = 0;
    for (int node = 0; node < NUM_NODES; node++)
        imc_wr_cas += g_monitor.imc_wr_bytes[node] / 64;

    double T_demand_rfo = 0.0, T_hw_rfo_pf = 0.0;
    for (int p = 0; p < g_monitor.ocr_proc_count; p++) {
        T_demand_rfo += S_demand_rfo[p];
        T_hw_rfo_pf  += S_hw_rfo_pf[p];
    }
    double R = (double)imc_wr_cas - T_demand_rfo - T_hw_rfo_pf;
    if (R < 0.0) R = 0.0;

    double T_shl_weight = 0.0;
    for (int i = 0; i < n; i++) {
        T_shl_weight += (d[i].demand_data_rd + d[i].hw_data_pf)
                      * (double)arr[i]->store_sample_count;
    }

    for (int i = 0; i < n; i++) {
        double w = (d[i].demand_data_rd + d[i].hw_data_pf)
                 * (double)arr[i]->store_sample_count;
        d[i].store_hit_load = (T_shl_weight > 0.0)
            ? R * w / T_shl_weight
            : 0.0;
    }

    /* Pass 6 — final BW + EMA smoothing.
     *
     * The L3-miss-based magnitude anchors (OCR.DEMAND_DATA_RD.L3_MISS,
     * OCR.HW_DATA_PF.L3_MISS) are placement-biased: the same object reads
     * substantially higher BW on the remote tier (CXL) than on local DRAM
     * because local-tier caches absorb more demand+prefetch traffic. Without
     * smoothing this drives every-epoch ping-pong on objects whose true BW
     * sits near the budget boundary. EMA blends the new sample with prior
     * state so a single placement-induced swing cannot flip the ranking. */
    double alpha = g_config.bw_ema_alpha;
    for (int i = 0; i < n; i++) {
        mem_object_t *o = arr[i];
        o->rd_bw = (d[i].demand_data_rd + d[i].hw_data_pf + d[i].sw_data_pf
                  + d[i].demand_rfo + d[i].hw_rfo_pf) * 64.0 / T;
        o->wr_bw = (d[i].demand_rfo + d[i].hw_rfo_pf + d[i].store_hit_load) * 64.0 / T;
        o->bw    = o->rd_bw + o->wr_bw;

        if (alpha <= 0.0 || o->bw_ema == 0.0)
            o->bw_ema = o->bw;
        else
            o->bw_ema = alpha * o->bw + (1.0 - alpha) * o->bw_ema;
    }

    /* Per-object epoch log — emitted here because the derived terms are local
     * to this function and not retained on mem_object_t. Mirrors the format
     * used elsewhere for per-epoch object summaries. */
    for (int i = 0; i < n; i++) {
        mem_object_t *o = arr[i];
        TM_EPOCH("  obj %#lx (%zu pages, node %d, pid %d): "
                 "loads=%lu stores=%lu allloads=%lu pf=%lu "
                 "lat=%.1f reg_ld_raw=%.2f reg_ld=%.2f reg_st_raw=%.2f reg_st=%.2f "
                 "dd_rd=%.2e hw_dp=%.2e sw_dp=%.2e d_rfo=%.2e hw_rp=%.2e shl=%.2e "
                 "rd_bw=%.2f GB/s wr_bw=%.2f GB/s bw=%.2f GB/s bw_ema=%.2f GB/s",
                 o->start_addr, o->nr_pages, o->current_node,
                 (int)o->pid,
                 o->load_sample_count, o->store_sample_count,
                 o->allload_sample_count, o->pf_sample_count,
                 d[i].avg_store_lat, d[i].reg_load_raw, d[i].reg_load,
                 d[i].reg_store_raw, d[i].reg_store,
                 d[i].demand_data_rd, d[i].hw_data_pf, d[i].sw_data_pf,
                 d[i].demand_rfo, d[i].hw_rfo_pf, d[i].store_hit_load,
                 o->rd_bw / 1e9, o->wr_bw / 1e9, o->bw / 1e9, o->bw_ema / 1e9);
    }

    real_free(d);
}

/* ── Ranking and migration decisions ── */

struct obj_collect_ctx {
    mem_object_t **array;
    int count;
    int capacity;
};

static void collect_obj(mem_object_t *obj, void *ctx)
{
    struct obj_collect_ctx *c = (struct obj_collect_ctx *)ctx;
    if (c->count < c->capacity)
        c->array[c->count++] = obj;
}

/* Size-aware ranking: sort by value per 4 KiB page and pack greedily until
 * the DRAM budget is exhausted, skipping objects that do not fit. */
static int cmp_bw_desc(const void *a, const void *b)
{
    const mem_object_t *obj_a = *(mem_object_t * const *)a;
    const mem_object_t *obj_b = *(mem_object_t * const *)b;

    if (obj_a->nr_pages == 0 && obj_b->nr_pages != 0) return  1;
    if (obj_a->nr_pages != 0 && obj_b->nr_pages == 0) return -1;
    if (obj_a->nr_pages != 0 && obj_b->nr_pages != 0) {
        long double lhs = (long double)obj_a->bw_ema * (long double)obj_b->nr_pages;
        long double rhs = (long double)obj_b->bw_ema * (long double)obj_a->nr_pages;
        if (lhs > rhs) return -1;
        if (lhs < rhs) return  1;
    }

    if (obj_a->bw_ema > obj_b->bw_ema) return -1;
    if (obj_a->bw_ema < obj_b->bw_ema) return  1;
    return 0;
}

static double obj_bw_ema_per_page(const mem_object_t *obj)
{
    if (obj->nr_pages == 0)
        return 0.0;
    return obj->bw_ema / (double)obj->nr_pages;
}

/* Query node for objects that haven't been queried yet (pages not faulted at insert time) */
static void resolve_obj_node(mem_object_t *obj, void *ctx)
{
    (void)ctx;
    if (obj->current_node >= 0) return; /* already known */

    /* Query the first faulted page. Try a few offsets. */
    for (size_t off = 0; off < obj->nr_pages && off < 16; off++) {
        void *page = (void *)(obj->start_addr + off * TM_PAGE_SIZE);
        int status = -1;
        long ret = syscall(__NR_move_pages, 0, 1, &page, NULL, &status, 0);
        if (ret == 0 && status >= 0) {
            obj->current_node = status;
            TM_DBG("Resolved obj %#lx node=%d", obj->start_addr, status);
            return;
        }
    }
    /* Still unknown — default to CXL */
    obj->current_node = CXL_NODE;
}

static void rank_and_decide(void)
{
    if (g_config.dram_budget_bytes == 0) return; /* No budget = no migration */

    /* Resolve any unknown node assignments */
    obj_store_foreach(resolve_obj_node, NULL);

    /* Collect all objects */
    int max_objs = 1024;
    mem_object_t **sorted = real_malloc(max_objs * sizeof(mem_object_t *));
    if (!sorted) return;

    struct obj_collect_ctx ctx = { .array = sorted, .count = 0, .capacity = max_objs };
    obj_store_foreach(collect_obj, &ctx);

    if (ctx.count == 0) {
        real_free(sorted);
        return;
    }

    /* Sort by EMA BW per page descending */
    qsort(sorted, ctx.count, sizeof(mem_object_t *), cmp_bw_desc);

    /* Greedy knapsack: fill DRAM budget */
    size_t dram_budget_pages = g_config.dram_budget_bytes / TM_PAGE_SIZE;
    size_t filled = 0;

    /* Compute hysteresis threshold:
     * Find the EMA BW/page at the budget boundary to determine the hysteresis
     * band. Ranking and gating use bw_ema/nr_pages, not total bw_ema or the
     * raw per-epoch bw, so a single noisy or placement-biased sample cannot
     * flip placement on its own. */
    double threshold_bw_per_page = 0.0;
    {
        size_t accum = 0;
        for (int i = 0; i < ctx.count; i++) {
            accum += sorted[i]->nr_pages;
            if (accum > dram_budget_pages) {
                threshold_bw_per_page = obj_bw_ema_per_page(sorted[i]);
                break;
            }
        }
    }
    double hysteresis_band_per_page =
        threshold_bw_per_page * g_config.hysteresis_pct / 100.0;
    TM_DBG("DRAM budget: %zu pages, threshold_bw=%.2f MB/s/page, hysteresis_band=%.2f MB/s/page",
           dram_budget_pages, threshold_bw_per_page / 1e6,
           hysteresis_band_per_page / 1e6);

    for (int i = 0; i < ctx.count; i++) {
        mem_object_t *obj = sorted[i];
        double obj_bw_per_page = obj_bw_ema_per_page(obj);

        if (filled + obj->nr_pages <= dram_budget_pages) {
            /* Should be in local DRAM */
            if (obj->current_node != LOCAL_NODE) {
                /* Apply hysteresis: only promote if EMA BW/page above threshold + delta */
                if (obj_bw_per_page > threshold_bw_per_page + hysteresis_band_per_page ||
                    threshold_bw_per_page == 0.0) {
                    obj->migration_pending = true;
                    obj->target_node = LOCAL_NODE;
                }
            }
            filled += obj->nr_pages;
        } else {
            /* Should be on CXL */
            if (obj->current_node != CXL_NODE) {
                /* Apply hysteresis: only demote if EMA BW/page below threshold - delta */
                if (obj_bw_per_page < threshold_bw_per_page - hysteresis_band_per_page) {
                    obj->migration_pending = true;
                    obj->target_node = CXL_NODE;
                }
            }
        }
    }

    real_free(sorted);
}

/* ── Monitor thread main loop ── */

static void *monitor_thread_func(void *arg)
{
    (void)arg;

    /* Pin to monitor CPU */
    cpu_set_t cpuset;
    CPU_ZERO(&cpuset);
    CPU_SET(g_config.monitor_cpu, &cpuset);
    sched_setaffinity(0, sizeof(cpuset), &cpuset);

    /* Set realtime priority */
    struct sched_param param = { .sched_priority = 99 };
    sched_setscheduler(0, SCHED_FIFO, &param);

    g_monitor.monitor_tid_kernel = (pid_t)syscall(SYS_gettid);
    TM_DBG("Monitor thread started (tid=%d, cpu=%d)",
           g_monitor.monitor_tid_kernel, g_config.monitor_cpu);

    struct timespec mon_wall_start, mon_cpu_start;
    clock_gettime(CLOCK_MONOTONIC, &mon_wall_start);
    clock_gettime(CLOCK_THREAD_CPUTIME_ID, &mon_cpu_start);

    /* Warmup phase: let application initialize before profiling */
    if (g_config.warmup_sec > 0.0 && g_monitor.running) {
        TM_INFO("[%s] Warmup: sleeping %.1f sec before enabling monitoring",
                tm_log_wall_time(), g_config.warmup_sec);
        struct timespec warmup_ts;
        warmup_ts.tv_sec  = (time_t)g_config.warmup_sec;
        warmup_ts.tv_nsec = (long)((g_config.warmup_sec -
                             (double)warmup_ts.tv_sec) * 1e9);
        nanosleep(&warmup_ts, NULL);
        TM_INFO("Warmup completed, enabling monitoring");
    }

    if (!g_monitor.running) goto out;

    /* Enable perf events after warmup */
    monitor_enable_events();

    struct timespec sleep_ts;
    sleep_ts.tv_sec  = g_config.ocr_interval_ms / 1000;
    sleep_ts.tv_nsec = (g_config.ocr_interval_ms % 1000) * 1000000L;

    while (g_monitor.running) {
        clock_gettime(CLOCK_MONOTONIC, &g_monitor.epoch_start);
        uint64_t epoch_load_samples_start = g_monitor.samples_collected;
        uint64_t epoch_store_samples_start = g_monitor.store_samples_collected;

        /* Reset per-process OCR epoch accumulators (single-proc entries only;
         * multi-proc entries are zeroed by collect_shm_ocr's atomic_exchange) */
        for (int i = 0; i < g_monitor.ocr_proc_count; i++) {
            if (g_monitor.ocr_procs[i].fd_demand_data_rd >= 0) {
                g_monitor.ocr_procs[i].epoch_demand_data_rd = 0;
                g_monitor.ocr_procs[i].epoch_demand_rfo     = 0;
                g_monitor.ocr_procs[i].epoch_hw_data_pf     = 0;
                g_monitor.ocr_procs[i].epoch_hw_rfo_pf      = 0;
            }
        }

        /* Multi-process: register proc_ocr_t entries for newly joined processes */
        check_new_procs_ocr();

        /* ── Phase A: Collect throughout epoch ── */
        struct timespec epoch_end;
        epoch_end.tv_sec  = g_monitor.epoch_start.tv_sec + (int)g_config.epoch_sec;
        epoch_end.tv_nsec = g_monitor.epoch_start.tv_nsec +
            (long)((g_config.epoch_sec - (int)g_config.epoch_sec) * 1e9);
        if (epoch_end.tv_nsec >= 1000000000L) {
            epoch_end.tv_sec++;
            epoch_end.tv_nsec -= 1000000000L;
        }

        while (g_monitor.running) {
            nanosleep(&sleep_ts, NULL);

            struct timespec now;
            clock_gettime(CLOCK_MONOTONIC, &now);
            if (now.tv_sec > epoch_end.tv_sec ||
                (now.tv_sec == epoch_end.tv_sec && now.tv_nsec >= epoch_end.tv_nsec))
                break;

            /* Read OCR counters (single-proc: read fds; multi-proc: leader's own to shm) */
            read_ocr_counters();
            if (g_config.multi_proc)
                ocr_self_read_to_shm();

            /* Drain PEBS ring buffers */
            for (int cpu = 0; cpu < NUM_CPUS_PER_NODE; cpu++) {
                drain_pebs_buffer(cpu);
                drain_pebs_store_buffer(cpu);
                drain_pebs_allload_buffer(cpu);
            }
        }

        if (!g_monitor.running) break;

        /* Final drain + read at epoch boundary */
        read_ocr_counters();
        if (g_config.multi_proc)
            ocr_self_read_to_shm();
        /* Harvest all processes' OCR from shared memory */
        collect_shm_ocr();
        /* System-wide iMC WR counters (ground truth for total writes) */
        read_imc_counters();
        for (int cpu = 0; cpu < NUM_CPUS_PER_NODE; cpu++) {
            drain_pebs_buffer(cpu);
            drain_pebs_store_buffer(cpu);
            drain_pebs_allload_buffer(cpu);
        }
        if (g_monitor.samples_collected == epoch_load_samples_start &&
            g_monitor.store_samples_collected == epoch_store_samples_start) {
            goto reset_counters;
        }

        /* ── Phase B: End-of-epoch computation ── */
        struct timespec now;
        clock_gettime(CLOCK_MONOTONIC, &now);
        double T = (now.tv_sec - g_monitor.epoch_start.tv_sec) +
                   (now.tv_nsec - g_monitor.epoch_start.tv_nsec) / 1e9;
        if (T <= 0.0) T = g_config.epoch_sec;

        /* Step 1: Compute per-object BW via six-pass attribution */
        {
            int max_objs = 4096;
            mem_object_t **sorted = real_malloc(max_objs * sizeof(mem_object_t *));
            struct obj_collect_ctx cctx = { sorted, 0, max_objs };
            if (sorted) obj_store_foreach(collect_obj, &cctx);

            if (sorted && cctx.count > 0) {
                compute_per_object_bw_new(sorted, cctx.count, T);
            }
            if (sorted) real_free(sorted);
        }

        /* Step 4/5: the congestion controller (when active) owns placement and
         * each process interleaves its own local objects; otherwise the base
         * bandwidth knapsack ranks and each process migrates its own pending. */
        double cc_r = 0.0, cc_dmax = 0.0;
        int    cc_g = 0;
        bool cc_owns = congest_ctrl_decide(T, &cc_r, &cc_dmax, &cc_g);

        /* Step 4: Rank and decide (skipped while the controller owns placement) */
        if (!cc_owns) rank_and_decide();

        /* Step 5: Execute migrations */
        if (g_config.multi_proc && g_shm) {
            /* Multi-process: publish the controller decision, then signal all
             * processes to migrate their own objects. */
            epoch_sync_t *es = shm_epoch_sync();
            atomic_store_explicit(&es->cc_owns, cc_owns ? 1 : 0, memory_order_release);
            atomic_store_explicit(&es->cc_r, cc_r, memory_order_release);
            atomic_store_explicit(&es->cc_density_max, cc_dmax, memory_order_release);
            atomic_store_explicit(&es->cc_g, cc_g, memory_order_release);

            atomic_store_explicit(&es->migrate_done, 0, memory_order_release);
            atomic_store_explicit(&es->phase, PHASE_MIGRATING,
                                 memory_order_release);
            atomic_fetch_add_explicit(&es->futex_word, 1, memory_order_release);
            shm_futex_wake(&es->futex_word, INT_MAX);

            /* Leader migrates its own objects (controller interleave or base). */
            if (cc_owns) congest_ctrl_migrate_local(cc_r, cc_dmax, cc_g, false);
            else         migrate_execute_own_pending();

            /* Leader counts towards barrier */
            atomic_fetch_add_explicit(&es->migrate_done, 1,
                                     memory_order_release);
            atomic_fetch_add_explicit(&es->futex_word, 1,
                                     memory_order_release);
            shm_futex_wake(&es->futex_word, INT_MAX);

            /* Wait for all processes to finish migrating */
            int target = atomic_load_explicit(&es->barrier_target,
                                              memory_order_acquire);
            while (atomic_load_explicit(&es->migrate_done,
                                        memory_order_acquire) < target) {
                int fw = atomic_load_explicit(&es->futex_word,
                                              memory_order_acquire);
                struct timespec wait_ts = { .tv_sec = 0, .tv_nsec = 10000000 };
                /* Poll with short timeout instead of blocking */
                nanosleep(&wait_ts, NULL);
                (void)fw;
            }

            /* Signal epoch done */
            atomic_store_explicit(&es->phase, PHASE_DONE, memory_order_release);
            atomic_fetch_add_explicit(&es->futex_word, 1, memory_order_release);
            shm_futex_wake(&es->futex_word, INT_MAX);

            /* Check for dead processes */
            shm_check_dead_procs();
        } else {
            /* Single-process: direct migration */
            if (cc_owns) congest_ctrl_migrate_local(cc_r, cc_dmax, cc_g, true);
            else         migrate_execute_pending();
        }

        /* Epoch logging */
        TM_EPOCH("[%s] === Epoch %lu (T=%.2fs) ===",
                 tm_log_wall_time(), g_monitor.epoch_counter, T);
        for (int i = 0; i < g_monitor.ocr_proc_count; i++) {
            proc_ocr_t *po = &g_monitor.ocr_procs[i];
            if (po->epoch_demand_data_rd || po->epoch_demand_rfo ||
                po->epoch_hw_data_pf || po->epoch_hw_rfo_pf) {
                TM_EPOCH("  pid %d: dd_rd=%lu d_rfo=%lu hw_dp=%lu hw_rp=%lu",
                         (int)po->pid,
                         po->epoch_demand_data_rd, po->epoch_demand_rfo,
                         po->epoch_hw_data_pf, po->epoch_hw_rfo_pf);
            }
        }
        TM_EPOCH("  iMC WR: node0=%.2f GB/s node1=%.2f GB/s",
                 g_monitor.imc_wr_bytes[0] / T / 1e9,
                 g_monitor.imc_wr_bytes[1] / T / 1e9);
        TM_EPOCH("  iMC RD: node0=%.2f GB/s node1=%.2f GB/s",
                 g_monitor.imc_rd_bytes[0] / T / 1e9,
                 g_monitor.imc_rd_bytes[1] / T / 1e9);
        TM_EPOCH("  PEBS load:  collected=%lu unmatched=%lu lost=%lu",
                 g_monitor.samples_collected, g_monitor.samples_unmatched,
                 g_monitor.samples_lost);
        TM_EPOCH("  PEBS store: collected=%lu unmatched=%lu lost=%lu",
                 g_monitor.store_samples_collected,
                 g_monitor.store_samples_unmatched,
                 g_monitor.store_samples_lost);
        TM_EPOCH("  PEBS allload: collected=%lu pf=%lu unmatched=%lu lost=%lu",
                 g_monitor.allload_samples_collected,
                 g_monitor.allload_samples_pf,
                 g_monitor.allload_samples_unmatched,
                 g_monitor.allload_samples_lost);
        {
            struct swpf_cache_stats st;
            swpf_cache_get_stats(&st);
            TM_EPOCH("  SWPF cache: hits=%lu misses=%lu read_fail=%lu pf=%lu non_pf=%lu",
                     st.hits, st.misses, st.read_failures,
                     st.pf_verdicts, st.non_pf_verdicts);
        }

        /* Diagnostic: per-CPU PEBS hardware-counter deltas + multiplex ratio.
         * raw_sum    = Σ Δvalue (as read; counter only runs when active)
         * scaled_sum = Σ Δvalue × (Δtime_enabled / Δtime_running)
         * ru/en      = time_running / time_enabled fraction (1.0 = no multiplex) */
        {
            static uint64_t prev_val_l[NUM_CPUS_PER_NODE];
            static uint64_t prev_en_l [NUM_CPUS_PER_NODE];
            static uint64_t prev_ru_l [NUM_CPUS_PER_NODE];
            static uint64_t prev_val_s[NUM_CPUS_PER_NODE];
            static uint64_t prev_en_s [NUM_CPUS_PER_NODE];
            static uint64_t prev_ru_s [NUM_CPUS_PER_NODE];
            uint64_t raw_l = 0, scaled_l = 0, en_l_sum = 0, ru_l_sum = 0;
            uint64_t raw_s = 0, scaled_s = 0, en_s_sum = 0, ru_s_sum = 0;
            double min_l = 2.0, max_l = 0.0, min_s = 2.0, max_s = 0.0;
            int n_l = 0, n_s = 0;

            for (int cpu = 0; cpu < NUM_CPUS_PER_NODE; cpu++) {
                if (g_monitor.pebs_fd[cpu] >= 0) {
                    struct perf_read_scaled r = perf_read_count_scaled(g_monitor.pebs_fd[cpu]);
                    uint64_t dv = r.value - prev_val_l[cpu];
                    uint64_t de = r.time_enabled - prev_en_l[cpu];
                    uint64_t dr = r.time_running - prev_ru_l[cpu];
                    prev_val_l[cpu] = r.value;
                    prev_en_l[cpu]  = r.time_enabled;
                    prev_ru_l[cpu]  = r.time_running;
                    if (de > 0 && dv > 0) {
                        uint64_t sc = (dr > 0) ? (uint64_t)((double)dv * (double)de / (double)dr) : dv;
                        double ratio = (double)dr / (double)de;
                        raw_l    += dv;
                        scaled_l += sc;
                        en_l_sum += de;
                        ru_l_sum += dr;
                        if (ratio < min_l) min_l = ratio;
                        if (ratio > max_l) max_l = ratio;
                        n_l++;
                    }
                }
                if (g_monitor.pebs_store_fd[cpu] >= 0) {
                    struct perf_read_scaled r = perf_read_count_scaled(g_monitor.pebs_store_fd[cpu]);
                    uint64_t dv = r.value - prev_val_s[cpu];
                    uint64_t de = r.time_enabled - prev_en_s[cpu];
                    uint64_t dr = r.time_running - prev_ru_s[cpu];
                    prev_val_s[cpu] = r.value;
                    prev_en_s[cpu]  = r.time_enabled;
                    prev_ru_s[cpu]  = r.time_running;
                    if (de > 0 && dv > 0) {
                        uint64_t sc = (dr > 0) ? (uint64_t)((double)dv * (double)de / (double)dr) : dv;
                        double ratio = (double)dr / (double)de;
                        raw_s    += dv;
                        scaled_s += sc;
                        en_s_sum += de;
                        ru_s_sum += dr;
                        if (ratio < min_s) min_s = ratio;
                        if (ratio > max_s) max_s = ratio;
                        n_s++;
                    }
                }
            }
            double avg_l = en_l_sum ? (double)ru_l_sum / (double)en_l_sum : 0.0;
            double avg_s = en_s_sum ? (double)ru_s_sum / (double)en_s_sum : 0.0;
            if (n_l > 0)
                TM_EPOCH("  PEBS load  HW: raw=%.3e scaled=%.3e ru/en avg=%.3f min=%.3f max=%.3f (%d cpus active)",
                         (double)raw_l, (double)scaled_l, avg_l, min_l, max_l, n_l);
            if (n_s > 0)
                TM_EPOCH("  PEBS store HW: raw=%.3e scaled=%.3e ru/en avg=%.3f min=%.3f max=%.3f (%d cpus active)",
                         (double)raw_s, (double)scaled_s, avg_s, min_s, max_s, n_s);
        }

reset_counters:
        /* Step 6: Reset per-epoch counters */
        obj_store_epoch_reset();
        g_monitor.epoch_counter++;

        /* Multi-process: transition to SAMPLING for next epoch */
        if (g_config.multi_proc && g_shm) {
            epoch_sync_t *es = shm_epoch_sync();
            atomic_store_explicit(&es->phase, PHASE_SAMPLING,
                                 memory_order_release);
            atomic_fetch_add_explicit(&es->futex_word, 1, memory_order_release);
            shm_futex_wake(&es->futex_word, INT_MAX);
        }
        TM_EPOCH("\n");
    }

    TM_DBG("Monitor thread exiting");
out:
    {
        struct timespec mon_wall_end, mon_cpu_end;
        clock_gettime(CLOCK_MONOTONIC, &mon_wall_end);
        clock_gettime(CLOCK_THREAD_CPUTIME_ID, &mon_cpu_end);
        double elapsed = (mon_wall_end.tv_sec - mon_wall_start.tv_sec) +
                         (mon_wall_end.tv_nsec - mon_wall_start.tv_nsec) / 1e9;
        double cpu_t   = (mon_cpu_end.tv_sec  - mon_cpu_start.tv_sec) +
                         (mon_cpu_end.tv_nsec  - mon_cpu_start.tv_nsec) / 1e9;
        double usage   = (elapsed > 0.0) ? (cpu_t / elapsed * 100.0) : 0.0;
        TM_INFO("Monitor thread exit: elapsed=%.3fs cpu=%.3fs usage=%.2f%%",
                elapsed, cpu_t, usage);
    }
    return NULL;
}

/* ── Init / Cleanup ── */

int monitor_init(void)
{
    memset(&g_monitor, 0, sizeof(g_monitor));

    /* Initialize fd slots explicitly so cleanup can safely run after partial setup. */
    for (int i = 0; i < NUM_CPUS_PER_NODE; i++) {
        g_monitor.pebs_fd[i]       = -1;
        g_monitor.pebs_store_fd[i] = -1;
        g_monitor.pebs_allload_fd[i] = -1;
    }
    for (int i = 0; i < MAX_PROCS; i++) {
        g_monitor.ocr_procs[i].fd_demand_data_rd = -1;
        g_monitor.ocr_procs[i].fd_demand_rfo     = -1;
        g_monitor.ocr_procs[i].fd_hw_data_pf     = -1;
        g_monitor.ocr_procs[i].fd_hw_rfo_pf      = -1;
    }
    for (int node = 0; node < NUM_NODES; node++)
        for (int ch = 0; ch < NUM_IMC_CHANNELS; ch++) {
            g_monitor.imc_wr_fds[node][ch] = -1;
            g_monitor.imc_rd_fds[node][ch] = -1;
        }

    g_monitor.running = true;

    if (setup_pebs_store_events() != 0)
        return -1;
    if (setup_pebs_events() != 0) {
        cleanup_pebs_store_events();
        return -1;
    }
    if (setup_pebs_allload_events() != 0) {
        cleanup_pebs_events();
        cleanup_pebs_store_events();
        return -1;
    }
    if (setup_ocr_events() != 0) {
        cleanup_pebs_allload_events();
        cleanup_pebs_events();
        cleanup_pebs_store_events();
        return -1;
    }
    if (setup_imc_events() != 0) {
        TM_INFO("Warning: iMC WR/RD events unavailable, store_hit_load will be zero");
        /* Non-fatal: library still works, just without store_hit_load. */
    }

    /* Latency-based congestion controller (no-op unless TIERMEM_CONGEST_CTRL=1).
     * Non-fatal: failure just leaves the controller disabled. */
    congest_ctrl_init();

    TM_DBG("Monitor initialized");
    return 0;
}

int monitor_launch(void)
{
    pthread_attr_t attr;
    pthread_attr_init(&attr);

    cpu_set_t cpuset;
    CPU_ZERO(&cpuset);
    CPU_SET(g_config.monitor_cpu, &cpuset);
    pthread_attr_setaffinity_np(&attr, sizeof(cpuset), &cpuset);

    /* Use real_pthread_create to avoid registering monitor thread */
    int ret = real_pthread_create(&g_monitor.monitor_tid, &attr,
                                   monitor_thread_func, NULL);
    pthread_attr_destroy(&attr);

    if (ret != 0) {
        TM_ERR("Failed to create monitor thread: %s", strerror(ret));
        return -1;
    }

    pthread_setname_np(g_monitor.monitor_tid, "tm:monitor");

    TM_DBG("Monitor thread launched");
    return 0;
}

void monitor_cleanup(void)
{
    cleanup_pebs_allload_events();
    cleanup_pebs_events();
    cleanup_pebs_store_events();
    cleanup_ocr_events();
    cleanup_imc_events();
    congest_ctrl_cleanup();

    TM_DBG("Monitor cleaned up");
}

/* ══════════════════════════════════════════════════════════════════════
 * Multi-process follower thread
 *
 * Runs in non-leader processes. Waits for the leader to signal
 * PHASE_MIGRATING, then pauses own threads, migrates own objects,
 * and waits for PHASE_DONE before resuming.
 * ══════════════════════════════════════════════════════════════════════ */

static pthread_t g_follower_tid;
static volatile bool g_follower_running = false;

static void *epoch_follower_thread_func(void *arg)
{
    (void)arg;

    pid_t my_tid = (pid_t)syscall(SYS_gettid);
    TM_DBG("Epoch follower thread started (tid=%d)", my_tid);

    struct timespec ocr_ts;
    ocr_ts.tv_sec  = g_config.ocr_interval_ms / 1000;
    ocr_ts.tv_nsec = (g_config.ocr_interval_ms % 1000) * 1000000L;

    while (g_follower_running) {
        epoch_sync_t *es = shm_epoch_sync();
        if (!es) break;

        /* During PHASE_SAMPLING: periodically read own OCR counters
         * and accumulate into shared memory for the leader to collect. */
        int phase = atomic_load_explicit(&es->phase, memory_order_acquire);
        while (phase != PHASE_MIGRATING && g_follower_running) {
            nanosleep(&ocr_ts, NULL);
            ocr_self_read_to_shm();
            phase = atomic_load_explicit(&es->phase, memory_order_acquire);
        }

        if (!g_follower_running) break;

        /* Final OCR read before migration */
        ocr_self_read_to_shm();

        /* Migrate our own objects: controller interleave if the leader's
         * decision owns this epoch, else the base bandwidth path. The
         * cc_* fields were published before the leader set PHASE_MIGRATING, so
         * the acquire-load on phase above makes them visible here. */
        if (atomic_load_explicit(&es->cc_owns, memory_order_acquire))
            congest_ctrl_migrate_local(
                atomic_load_explicit(&es->cc_r, memory_order_acquire),
                atomic_load_explicit(&es->cc_density_max, memory_order_acquire),
                atomic_load_explicit(&es->cc_g, memory_order_acquire), false);
        else
            migrate_execute_own_pending();

        /* Signal that we're done */
        atomic_fetch_add_explicit(&es->migrate_done, 1, memory_order_release);
        atomic_fetch_add_explicit(&es->futex_word, 1, memory_order_release);
        shm_futex_wake(&es->futex_word, INT_MAX);

        /* Wait for PHASE_DONE (or PHASE_SAMPLING for next epoch) */
        phase = atomic_load_explicit(&es->phase, memory_order_acquire);
        while (phase == PHASE_MIGRATING && g_follower_running) {
            int fw = atomic_load_explicit(&es->futex_word,
                                          memory_order_acquire);
            shm_futex_wait(&es->futex_word, fw);
            phase = atomic_load_explicit(&es->phase, memory_order_acquire);
        }

        /* Wait briefly for PHASE_SAMPLING to be set (leader resets after DONE) */
        while (phase == PHASE_DONE && g_follower_running) {
            struct timespec ts = { .tv_sec = 0, .tv_nsec = 1000000 }; /* 1ms */
            nanosleep(&ts, NULL);
            phase = atomic_load_explicit(&es->phase, memory_order_acquire);
        }
    }

    TM_DBG("Epoch follower thread exiting");
    return NULL;
}

int epoch_follower_launch(void)
{
    g_follower_running = true;

    int ret = real_pthread_create(&g_follower_tid, NULL,
                                   epoch_follower_thread_func, NULL);
    if (ret != 0) {
        TM_ERR("Failed to create follower thread: %s", strerror(ret));
        return -1;
    }

    pthread_setname_np(g_follower_tid, "tm:follower");
    TM_DBG("Epoch follower thread launched");
    return 0;
}

void epoch_follower_stop(void)
{
    g_follower_running = false;

    /* Wake the follower if it's stuck waiting */
    epoch_sync_t *es = shm_epoch_sync();
    if (es) {
        atomic_fetch_add_explicit(&es->futex_word, 1, memory_order_release);
        shm_futex_wake(&es->futex_word, INT_MAX);
    }

    pthread_join(g_follower_tid, NULL);
    TM_DBG("Epoch follower stopped");
}
