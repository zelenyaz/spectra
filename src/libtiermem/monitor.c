#define OCR_EVENT_CONFIG               0x012A

/* ── OCR events (per-task counting mode) ── */
#define OCR_DEMAND_DATA_RD_L3_MISS_CFG1 0x3FFFC00001ULL
#define OCR_DEMAND_RFO_L3_MISS_CFG1     0x3FFFC00002ULL
/* OCR mask 0x3FFFC04410 covers L3-miss data prefetches generated by
 * either HW prefetchers (L1/L2 data-side, with the original 0x410 bits)
 * or SW prefetch instructions (PREFETCHNTA/T0/T1/T2/W/WT1, the new 0x4000
 * bit). The counter still measures one unified "total data PF" magnitude;
 * the HW vs SW split is recovered downstream from MEM_INST_RETIRED.ALL_LOADS
 * PEBS samples. */
#define OCR_TOTAL_DATA_PF_L3_MISS_CFG1  0x3FFFC04410ULL
#define OCR_HW_RFO_PF_L3_MISS_CFG1      0x3FFFC00020ULL

/* ── iMC uncore setup (UNC_M_CAS_COUNT.WR / .RD, Sapphire Rapids) ── */
